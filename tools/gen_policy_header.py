#!/usr/bin/env python3
"""Generate cpp/policy_generated.h from policy.json.

The C++ firewall daemon compiles its zone and rule tables in from this
header, so policy.json is the single source of truth for both the
Python and C++ firewalls. The policy goes through the same
load_policy() validation the controller uses.

    python3 tools/gen_policy_header.py policy.json -o cpp/policy_generated.h

cpp/Makefile runs this on every build. With -o, the file is only
rewritten when its content changes, so an unchanged policy doesn't
trigger a recompile.
"""

import argparse
import ipaddress
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from firewall_rules import PolicyError, load_policy  # noqa: E402

_IDENTIFIER = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')
RESERVED = {'Unknown'}  # the daemon's "outside every zone" value


def render(zones, block_all_ip, block_icmp, source='policy.json'):
    for name in zones:
        if not _IDENTIFIER.match(name) or name in RESERVED:
            raise PolicyError('zone name {!r} must be a C++ identifier and not one of {}'
                              .format(name, sorted(RESERVED)))
    order = list(zones)

    def pairs(name, table):
        rows = sorted(table, key=lambda p: (order.index(p[0]), order.index(p[1])))
        if rows:
            body = ''.join('    {{Zone::{}, Zone::{}}},\n'.format(s, d) for s, d in rows)
            decl = 'const std::pair<Zone, Zone> {}[] = {{\n{}}};\n'.format(name, body)
        else:
            # C++ has no zero-size arrays; the count keeps this unread.
            decl = 'const std::pair<Zone, Zone> {}[1] = {{}};\n'.format(name)
        return decl + 'constexpr size_t {}Count = {};\n'.format(name, len(rows))

    zone_rows = ''.join(
        '    {{Zone::{}, 0x{:08X}u, {}, "{}"}},  // {}\n'.format(
            name, int(z['subnet'].network_address), z['subnet'].prefixlen, name, z['subnet'])
        for name, z in zones.items())

    return (
        '// GENERATED by tools/gen_policy_header.py from {source} -- do not edit.\n'
        '// Change {source} instead; `make -C cpp` regenerates this file.\n'
        '#pragma once\n'
        '\n'
        '#include <cstddef>\n'
        '#include <cstdint>\n'
        '#include <utility>\n'
        '\n'
        'namespace {{\n'
        '\n'
        'enum class Zone : uint8_t {{ {enum}, Unknown }};\n'
        '\n'
        'struct SubnetZone {{\n'
        '    Zone zone;\n'
        '    uint32_t network;    // host byte order\n'
        '    uint32_t prefix_len;\n'
        '    const char* name;    // for logging only\n'
        '}};\n'
        '\n'
        'const SubnetZone kZones[] = {{\n'
        '{zone_rows}'
        '}};\n'
        '\n'
        '{block_all}'
        '\n'
        '{block_icmp}'
        '\n'
        '}}  // namespace\n'
    ).format(source=source, enum=', '.join(order), zone_rows=zone_rows,
             block_all=pairs('kBlockAllIp', block_all_ip),
             block_icmp=pairs('kBlockIcmp', block_icmp))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('policy', help='path to policy.json')
    parser.add_argument('-o', '--output', help='write here (only if changed) instead of stdout')
    args = parser.parse_args()
    try:
        header = render(*load_policy(args.policy), source=os.path.basename(args.policy))
    except PolicyError as exc:
        sys.exit('policy error: {}'.format(exc))

    if not args.output:
        sys.stdout.write(header)
        return
    try:
        with open(args.output) as f:
            if f.read() == header:
                return
    except FileNotFoundError:
        pass
    with open(args.output, 'w', newline='\n') as f:
        f.write(header)


if __name__ == '__main__':
    main()
